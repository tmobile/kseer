#!/usr/bin/env bash
#
# run-local.sh — run kseer-agent locally against a real cluster (via a token)
# and stream its data into a throwaway local ClickHouse.
#
# What it does:
#   1. Brings up a local ClickHouse (docker compose) and applies schema.sql.
#   2. Generates debug-config.yaml: one cluster authenticated by a service
#      account token, ClickHouse output pointed at localhost. events_table is
#      set to the same table so the startup resume-RV / seed-completion logic
#      is exercised (this is what makes a kind "skip the initial LIST").
#   3. Runs the agent with `go run` against that config.
#
# Inputs (prompted if not set in the environment):
#   K8S_API_SERVER   API server URL, e.g. https://my-cluster:6443
#   K8S_TOKEN        Service account / bearer token (input is hidden)
#
# Optional environment overrides:
#   CLUSTER_NAME       default: debug-cluster
#   K8S_NAMESPACES     comma-separated namespace allowlist (default: all)
#   RESYNC_INTERVAL    P2 resync_interval, e.g. 2m (default: 0 = disabled)
#   VERBOSE_EVENTS     true|false — log one line per event sent (default: true)
#   CH_HOST            default: localhost
#   CH_PORT            host port for ClickHouse native protocol (default: 9100)
#   CH_HTTP_PORT       host port for ClickHouse HTTP/play UI (default: 8123)
#   CH_DB              default: kseer
#   CH_TABLE           default: kubernetes_events
#   CH_TABLE_VERSION   default: object_json  (must match schema.sql)
#   SKIP_CLICKHOUSE    true to skip docker compose / schema (use existing CH)
#
# Re-running is safe: ClickHouse data persists in a docker volume, so on the
# second run you can watch kinds resume from their stored RV instead of
# re-LISTing — exactly the behavior to debug.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AGENT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CONFIG_FILE="$SCRIPT_DIR/debug-config.yaml"
TOKEN_FILE="$SCRIPT_DIR/.token"

CLUSTER_NAME="${CLUSTER_NAME:-debug-cluster}"
K8S_NAMESPACES="${K8S_NAMESPACES:-}"
RESYNC_INTERVAL="${RESYNC_INTERVAL:-0}"
VERBOSE_EVENTS="${VERBOSE_EVENTS:-true}"
CH_HOST="${CH_HOST:-localhost}"
CH_PORT="${CH_PORT:-9100}"
CH_HTTP_PORT="${CH_HTTP_PORT:-8123}"
CH_DB="${CH_DB:-kseer}"
# Exported so docker-compose.yaml can publish matching host ports.
export CH_PORT CH_HTTP_PORT
CH_TABLE="${CH_TABLE:-kubernetes_events}"
CH_TABLE_VERSION="${CH_TABLE_VERSION:-object_json}"
SKIP_CLICKHOUSE="${SKIP_CLICKHOUSE:-false}"

log()  { printf '\033[1;34m[debug]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

# ---- compose helper (supports both `docker compose` and `docker-compose`) ----
compose() {
  if docker compose version >/dev/null 2>&1; then
    docker compose -f "$SCRIPT_DIR/docker-compose.yaml" "$@"
  elif command -v docker-compose >/dev/null 2>&1; then
    docker-compose -f "$SCRIPT_DIR/docker-compose.yaml" "$@"
  else
    die "Neither 'docker compose' nor 'docker-compose' found. Install Docker, or set SKIP_CLICKHOUSE=true to use an existing ClickHouse."
  fi
}

# ---- gather cluster connection details ----------------------------------------
if [[ -z "${K8S_API_SERVER:-}" ]]; then
  # Offer the current kubeconfig's server as a convenience.
  if command -v kubectl >/dev/null 2>&1; then
    detected="$(kubectl config view --minify -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null || true)"
    if [[ -n "$detected" ]]; then
      read -r -p "API server URL [$detected]: " K8S_API_SERVER
      K8S_API_SERVER="${K8S_API_SERVER:-$detected}"
    fi
  fi
fi
[[ -z "${K8S_API_SERVER:-}" ]] && read -r -p "API server URL (e.g. https://host:6443): " K8S_API_SERVER
[[ -z "${K8S_API_SERVER:-}" ]] && die "API server URL is required."

if [[ -z "${K8S_TOKEN:-}" ]]; then
  read -r -s -p "Cluster token (input hidden): " K8S_TOKEN
  echo
fi
[[ -z "${K8S_TOKEN:-}" ]] && die "Token is required."

# ---- write token file (0600) and config --------------------------------------
umask 077
printf '%s' "$K8S_TOKEN" > "$TOKEN_FILE"
log "Wrote token to $TOKEN_FILE (gitignored, mode 600)."

namespaces_yaml=""
if [[ -n "$K8S_NAMESPACES" ]]; then
  namespaces_yaml=$'\n    namespaces:'
  IFS=',' read -ra _ns <<< "$K8S_NAMESPACES"
  for ns in "${_ns[@]}"; do
    ns="$(echo "$ns" | xargs)" # trim
    [[ -n "$ns" ]] && namespaces_yaml+=$'\n      - '"$ns"
  done
fi

cat > "$CONFIG_FILE" <<EOF
# Generated by run-local.sh — DO NOT COMMIT (contains a reference to .token).
mode: multi-cluster

clusters:
  - name: ${CLUSTER_NAME}
    service_account:
      server: ${K8S_API_SERVER}
      token_file: ${TOKEN_FILE}
      insecure: true   # debug only: skips API server TLS verification${namespaces_yaml}
    watch_config:
      resync_interval: "${RESYNC_INTERVAL}"

outputs:
  - type: clickhouse
    config:
      host: ${CH_HOST}
      port: ${CH_PORT}
      database: ${CH_DB}
      table: ${CH_TABLE}
      # events_table enables the startup resume-RV + seed-completion queries.
      # Pointing it at the same table reproduces the "kind skips initial LIST
      # on restart because it already has a resume RV in CH" behavior.
      events_table: ${CH_TABLE}
      table_version: ${CH_TABLE_VERSION}
      tls: false
      batch_size: 1000
      verbose_event_logging: ${VERBOSE_EVENTS}

buffer:
  size: 50000
  flush_interval: "500ms"
  retry_interval: "10s"
  batch_size: 1000

concurrency_control:
  enabled: true
  max_global_lists: 30
  max_lists_per_cluster: 10
  max_cluster_inits: 5

status_log:
  enabled: true
  interval: "1m"
  per_kind_detail: true
EOF
log "Generated config: $CONFIG_FILE"

# ---- bring up ClickHouse + schema --------------------------------------------
if [[ "$SKIP_CLICKHOUSE" != "true" ]]; then
  log "Starting local ClickHouse..."
  compose up -d

  log "Waiting for ClickHouse to become ready..."
  for i in $(seq 1 40); do
    if compose exec -T clickhouse clickhouse-client --query "SELECT 1" >/dev/null 2>&1; then
      break
    fi
    sleep 2
    [[ "$i" == "40" ]] && die "ClickHouse did not become ready in time. Check: $(basename "$0") logs via 'docker compose -f $SCRIPT_DIR/docker-compose.yaml logs'."
  done

  log "Applying schema.sql..."
  compose exec -T clickhouse clickhouse-client --multiquery < "$SCRIPT_DIR/schema.sql"
  log "ClickHouse ready at ${CH_HOST}:${CH_PORT} (HTTP play UI: http://localhost:${CH_HTTP_PORT}/play)."
else
  warn "SKIP_CLICKHOUSE=true — assuming ${CH_HOST}:${CH_PORT} is already up with the schema applied."
fi

# ---- run the agent ------------------------------------------------------------
log "Starting kseer-agent (Ctrl-C to stop)..."
log "Inspect results with:"
cat <<EOH
  docker compose -f "$SCRIPT_DIR/docker-compose.yaml" exec clickhouse \\
    clickhouse-client -q "SELECT kind, operation, count() c \\
      FROM ${CH_DB}.${CH_TABLE} WHERE cluster_name='${CLUSTER_NAME}' \\
      GROUP BY kind, operation ORDER BY kind, operation"
EOH
echo

cd "$AGENT_ROOT"
exec go run ./cmd/agent/main.go --config "$CONFIG_FILE"
